def _warn_mpesa_placeholder(name: str, value: str | None) -> None:
    if value is None or not value.strip():
        _settings_logger.warning("%s is empty; MPesa will not work until it is set.", name)
        return
    if value.strip().upper().startswith("YOUR_"):
        _settings_logger.warning("%s looks like a placeholder; update it in .env.", name)
        return
    if name == "MPESA_CALLBACK_URL" and "yourdomain.com" in value:
        _settings_logger.warning("%s still points at yourdomain.com; update it in .env.", name)


